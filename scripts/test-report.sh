#!/usr/bin/env bash
# Run both test suites with coverage and write docs/TEST_REPORT.md from their
# real output.
#
#   scripts/test-report.sh          (needs the test database: `make db-up`)
#
# CI also publishes JUnit and coverage files as build artifacts on every push.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPORT="$ROOT/docs/TEST_REPORT.md"
strip_ansi() { sed -E 's/\x1B\[[0-9;]*[A-Za-z]//g'; }

backend=$(cd "$ROOT/backend" && uv run pytest -v -p no:cacheprovider --cov --cov-report=term 2>&1 | strip_ansi)
frontend=$(cd "$ROOT/frontend" && npm run --silent test:coverage -- --reporter=verbose 2>&1 | strip_ansi)

backend_summary=$(grep -oE '[0-9]+ passed[^=]*' <<<"$backend" | tail -1 | sed -E 's/ +$//')
backend_total=$(grep -E '^TOTAL' <<<"$backend")
frontend_tests=$(grep -E '^\s+Tests ' <<<"$frontend" | sed -E 's/^\s+//; s/ +/ /g')
frontend_files=$(grep -E '^\s+Test Files ' <<<"$frontend" | sed -E 's/^\s+//; s/ +/ /g')

{
  echo "# Test report"
  echo
  echo "Generated by \`scripts/test-report.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')"
  echo "at commit \`$(git -C "$ROOT" rev-parse --short HEAD)\`."
  echo "CI runs the same suites on every push (plus an end-to-end smoke test of the"
  echo "Docker stack) and uploads JUnit and coverage reports as artifacts."
  echo
  echo "## Summary"
  echo
  echo "| Suite | Result | Coverage |"
  echo "| ----- | ------ | -------- |"
  echo "| Backend (pytest, real PostgreSQL) | $backend_summary | $(awk '{print $NF}' <<<"$backend_total") of statements and branches |"
  echo "| Frontend (Vitest + Testing Library) | $frontend_tests ($frontend_files) | $(grep -E '^Statements' <<<"$frontend" | awk '{print $3}') statements, $(grep -E '^Branches' <<<"$frontend" | awk '{print $3}') branches |"
  echo
  echo "## Backend coverage"
  echo
  echo '```text'
  sed -n '/coverage:/,/^TOTAL/p' <<<"$backend"
  echo '```'
  echo
  echo "## Frontend coverage"
  echo
  echo '```text'
  sed -n '/Coverage summary/,/^=*$/p' <<<"$frontend" | grep -v '^$'
  echo '```'
  echo
  echo "## Frontend tests"
  echo
  echo '```text'
  grep -E '^\s+(✓|×)' <<<"$frontend" | sed -E 's/ [0-9]+ms$//; s/^ +//' | sort
  echo '```'
  echo
  echo "## Backend tests"
  echo
  echo '```text'
  grep -E '::.* (PASSED|FAILED|ERROR)' <<<"$backend" | sed -E 's/ +\[ *[0-9]+%\]$//'
  echo '```'
} > "$REPORT"

echo "Wrote $REPORT"
